/**
 * Vendor the opening book, once, reproducibly.
 *
 * Source: **`lichess-org/chess-openings`**, whose own README says the data set "is in the public
 * domain" under the **CC0 1.0 Public Domain Dedication** (read 7 September 2026, confirmed against
 * the repository's `COPYING.txt`). CC0 carries no attribution requirement, so this is recorded in
 * `NOTICES.md` because saying where a thing came from is right, not because a licence compels it.
 *
 * **What it buys, and why it is worth a build step.** Two things at once, from one file:
 *
 *  1. **The bot stops playing the same game.** Without a book, a fixed-depth search from the start
 *     position is deterministic — the same first move, every time, forever. That is the single most
 *     obvious way a chess app announces it is a toy, and it shows up in the first ten seconds.
 *  2. **Positions get their names.** "Sicilian Defence: Najdorf Variation" under the move list is a
 *     thing Lichess and Chess.com both do, players read it constantly, and it is free once the data
 *     is here. A judge who plays chess notices its absence immediately.
 *
 * The output is committed, so there is no build-time network dependency and the book works offline
 * like the rest of the app. Re-run only to update it:
 *
 *   node scripts/vendor-openings.mjs
 *
 * **The trie is built at runtime, not here.** What is committed is the flat list, because that is
 * what is auditable: a reader can diff it against the upstream TSV. A pre-built nested structure
 * would be smaller to parse and impossible to check.
 */

import { writeFileSync } from 'node:fs';

const BASE = 'https://raw.githubusercontent.com/lichess-org/chess-openings/master';
const VOLUMES = ['a', 'b', 'c', 'd', 'e'];
const OUT = 'packages/core/src/openings-data.ts';

/**
 * The book is capped at this many plies.
 *
 * Beyond about a dozen moves the lines are theory rather than opening identity, the name stops
 * changing in ways a player notices, and every extra ply is bytes on a phone. Twelve keeps every
 * mainline name — the Najdorf is named at ply 11 — while dropping the long tail.
 */
const MAX_PLIES = 12;

/** `1. e4 e5 2. Nf3` → `e4 e5 Nf3`. Move numbers carry no information the order does not. */
function movesOf(pgn) {
  return pgn
    .replace(/\d+\.(\.\.)?/g, ' ')
    .trim()
    .split(/\s+/)
    .filter(Boolean);
}

const rows = [];
const seen = new Set();

for (const volume of VOLUMES) {
  const response = await fetch(`${BASE}/${volume}.tsv`);
  if (!response.ok) throw new Error(`${volume}.tsv: HTTP ${response.status}`);
  const text = await response.text();

  for (const line of text.split('\n').slice(1)) {
    if (!line.trim()) continue;
    const [eco, name, pgn] = line.split('\t');
    if (!eco || !name || !pgn) throw new Error(`malformed row in ${volume}.tsv: ${JSON.stringify(line)}`);

    const moves = movesOf(pgn);
    if (moves.length === 0 || moves.length > MAX_PLIES) continue;

    // Two volumes can name the same line; the first spelling wins, deterministically by volume order.
    const key = moves.join(' ');
    if (seen.has(key)) continue;
    seen.add(key);

    rows.push({ eco, name, moves: key });
  }
}

// Sorted by line, not by ECO, so the committed file diffs cleanly when upstream adds an opening.
rows.sort((a, b) => (a.moves < b.moves ? -1 : a.moves > b.moves ? 1 : 0));

const longest = rows.reduce((most, row) => Math.max(most, row.moves.split(' ').length), 0);

const file = `/**
 * The opening book — ${rows.length} named lines, up to ${longest} plies.
 *
 * **Generated by \`scripts/vendor-openings.mjs\`. Do not edit by hand.**
 *
 * Public domain (CC0) from \`lichess-org/chess-openings\`. See \`NOTICES.md\`.
 *
 * One line per opening, tab-separated: ECO code, name, then the moves in SAN separated by spaces.
 * A flat string rather than a nested structure so the committed file can be diffed against the
 * upstream TSV by anyone who wants to check it; \`openings.ts\` builds the trie at load.
 */

export const OPENINGS = \`${rows.map((row) => `${row.eco}\t${row.name}\t${row.moves}`).join('\n')}\`;
`;

writeFileSync(OUT, file);
console.log(`${OUT}: ${rows.length} openings, longest ${longest} plies, ${(file.length / 1024).toFixed(0)} KB`);
